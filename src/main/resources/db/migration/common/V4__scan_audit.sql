create table scan_audit (
    id                bigint generated by default as identity primary key,
    occurred_at       timestamp with time zone not null,
    device_id         bigint                   not null,
    gate_id           bigint                   not null,
    pass_id           uuid,
    holder_id         bigint,
    outcome           varchar(16)              not null,
    reason            varchar(32),
    token_fingerprint varchar(16)              not null,
    constraint fk_scan_audit_device foreign key (device_id) references gate_device (id),
    constraint fk_scan_audit_gate foreign key (gate_id) references gate (id),
    constraint ck_scan_audit_outcome check (
        (outcome = 'GRANTED' and reason is null) or (outcome = 'DENIED' and reason is not null))
);

create index ix_scan_audit_occurred_at on scan_audit (occurred_at);
create index ix_scan_audit_gate_occurred_at on scan_audit (gate_id, occurred_at);
create index ix_scan_audit_device_occurred_at on scan_audit (device_id, occurred_at);
create index ix_scan_audit_pass_occurred_at on scan_audit (pass_id, occurred_at);
create index ix_scan_audit_holder_occurred_at on scan_audit (holder_id, occurred_at);

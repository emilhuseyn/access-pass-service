create table site (
    id          bigint generated by default as identity primary key,
    name        varchar(120)             not null,
    time_zone   varchar(64)              not null,
    created_at  timestamp with time zone not null,
    constraint uq_site_name unique (name)
);

create table gate (
    id          bigint generated by default as identity primary key,
    site_id     bigint                   not null,
    code        varchar(40)              not null,
    name        varchar(120)             not null,
    created_at  timestamp with time zone not null,
    constraint fk_gate_site foreign key (site_id) references site (id),
    constraint uq_gate_site_code unique (site_id, code)
);

create table holder (
    id           bigint generated by default as identity primary key,
    full_name    varchar(160)             not null,
    email        varchar(254),
    external_ref varchar(64),
    active       boolean                  not null,
    created_at   timestamp with time zone not null,
    constraint uq_holder_email unique (email),
    constraint uq_holder_external_ref unique (external_ref)
);

create index ix_holder_full_name on holder (full_name);

create table pass_policy (
    id           bigint generated by default as identity primary key,
    site_id      bigint                   not null,
    name         varchar(120)             not null,
    window_start time,
    window_end   time,
    max_uses     integer,
    created_at   timestamp with time zone not null,
    constraint fk_pass_policy_site foreign key (site_id) references site (id),
    constraint uq_pass_policy_site_name unique (site_id, name),
    constraint ck_pass_policy_window check (
        (window_start is null and window_end is null)
        or (window_start is not null and window_end is not null and window_start <> window_end)),
    constraint ck_pass_policy_max_uses check (max_uses is null or max_uses > 0)
);

create table pass_policy_gate (
    policy_id bigint not null,
    gate_id   bigint not null,
    constraint pk_pass_policy_gate primary key (policy_id, gate_id),
    constraint fk_pass_policy_gate_policy foreign key (policy_id) references pass_policy (id) on delete cascade,
    constraint fk_pass_policy_gate_gate foreign key (gate_id) references gate (id)
);

create index ix_pass_policy_gate_gate on pass_policy_gate (gate_id);

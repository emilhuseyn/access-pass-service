create table staff_account (
    id            bigint generated by default as identity primary key,
    username      varchar(64)              not null,
    password_hash varchar(100)             not null,
    role          varchar(16)              not null,
    enabled       boolean                  not null,
    created_at    timestamp with time zone not null,
    constraint uq_staff_account_username unique (username),
    constraint ck_staff_account_role check (role in ('ADMIN', 'OPERATOR'))
);

create table gate_device (
    id             bigint generated by default as identity primary key,
    gate_id        bigint                   not null,
    name           varchar(120)             not null,
    api_key_hash   varchar(64)              not null,
    active         boolean                  not null,
    created_at     timestamp with time zone not null,
    deactivated_at timestamp with time zone,
    constraint fk_gate_device_gate foreign key (gate_id) references gate (id),
    constraint uq_gate_device_api_key_hash unique (api_key_hash)
);

create index ix_gate_device_gate on gate_device (gate_id);
